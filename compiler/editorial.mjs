/**
 * compiler / editorial.mjs
 * ---------------------------------------------------------------------------
 * 「编辑层表述」的**唯一识别实现** —— 预告 / 卷末旗标 这类**不属于剧本**的行。
 *
 * ★ 作者 2026-10-03：「敬请期待 这种和剧本无关的表述删掉，现在交付的是连贯的
 *   剧本不需要画外音」。实测全片就 2 处：
 *
 *     · `【敬请期待 第四章：示例章名】` → 章间预告
 *        （而且内容跟**下一章的章卡**重复 —— 第四章马上就要开演，不必提前吆喝）
 *     · `旁白：【本卷终】`                       → 卷末旗标
 *
 * ★★ **不能按「被【】包住」一刀切。** 剧本里有大量**叙事内**的方括号内容：
 *
 *     `【直升机机舱内】`（场景指示）· `【消息来自"朋友"】`（剧内信息）
 *     · `【日志残片23-F: …】`（日志残页）· `【全国瞬时警报系统】…`（广播）
 *     · `【快讯】…`（新闻）· `【忘却】`（剧中专名）· `【事件类型】：…`（尸检报告）
 *
 *   那些是**剧情**，删了就破戏。所以判据是**编辑层词表**，不按形状判。
 *
 * ★★ 另一个很诱人的错误：把「待续」当关键词。
 *   `旁白：队长沉默地带领手下回到指挥车。…` 里就藏着「下回」（手**下回**到）——
 *   按子串搜会误杀一句完全正常的旁白（第一版扫描真的报了它）。
 *   所以词表只收**不会出现在剧情里**的完整词，且要求**整行**匹配。
 *
 * 用法：
 *   import { editorialReason } from './editorial.mjs';
 *   if (editorialReason(raw)) continue;          // 转换器：丢弃
 *   if (editorialReason(beat.text)) throw ...    // 编译期：不该有漏网的
 */

/** 预告类：出现在【】里，或裸露成行 */
const TEASER = /^(?:【\s*)?(?:敬请期待|未完待续|下集预告|下回预告|敬请关注|敬请收看)/;

/** 卷末 / 全书旗标：整行就是一个【…】 */
const END_FLAG = /^【\s*(?:本卷终|本卷完|本篇终|全书终|全书完|全文完|全剧终|本作终|剧终|全篇终)\s*】$/;

/** 裸露的旗标（没有括号，但整行就是它） */
const BARE_FLAG = /^(?:未完待续|本卷终|本卷完|全书终|全书完|全文完|全剧终|剧终)[。！…\s]*$/;

/** 整行被【】包住 */
const WRAPPED = /^【[^】]*】$/;

/**
 * 判断源文档的一整行是不是编辑层表述。
 *
 * @param {string} raw 源行（可带 `说话人（类型）：` 前缀，如 `旁白：【本卷终】`）
 * @returns {string|null} 命中返回原因（人可读），否则 null
 */
export function editorialReason(raw) {
  const s = String(raw ?? '').trim();
  if (!s) return null;

  // 剥掉 `说话人（类型）：` 前缀再判一次（实例：`旁白：【本卷终】`）
  // ★ 注意 `【敬请期待 第四章：示例章名】` 里**也有冒号**，
  //   所以这条剥前缀的逻辑会把它切错 —— 但没关系，两个形态都要试，命中任一即可。
  const body = s.replace(/^[^：:]{1,30}(?:[（(][^）)]{1,30}[）)])?\s*[：:]\s*/, '').trim();
  const forms = body && body !== s ? [s, body] : [s];

  for (const t of forms) {
    if (END_FLAG.test(t)) return '卷末旗标';
    if (WRAPPED.test(t) && TEASER.test(t)) return '预告';
    if (BARE_FLAG.test(t)) return '编辑层整行';
  }
  return null;
}

/** 给报错信息用的说明（转换器 / 编译期共用，免得两处措辞不一致） */
export const EDITORIAL_NOTE =
  '编辑层表述（预告 / 卷末旗标）不是剧本内容 —— 交付的是连贯剧本，不需要画外音。';
