/**
 * branches.mjs —— 分支数据源（**示例**）
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *  这个文件回答一个问题：**分支怎么写成「可执行 + 带分镜」的数据。**
 *
 *  下面是一份精简示例（2 个分支点 / 2 条 END）。实际使用时替换成你自己的。
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *  分镜字段规范
 *  ─────────────────────────────────────────────────────────────────────
 *   { t: 'clear' }                       清台（编译器算出在场者后逐个退场）
 *   { t: 'bg',    name: 'bg_xxx.png' }   换背景
 *   { t: 'show',  who: 'hero', slot }    立绘上场（slot: center / left / right）
 *   { t: 'hide',  who: 'hero' }          单个退场
 *   { t: 'sfx',   text: '轰' }           音效（无音频素材时渲染为演出文本）
 *   { t: 'wait',  ms: 800 }              停顿
 *   { t: 'narrate', text }               旁白（不带说话人）
 *   { t: 'say',   who, text }            对白
 *
 *  ★ 两条写法纪律（都是踩出来的）
 *
 *  ① **分镜只能引用玩家已经看过的东西。**
 *     引用没有出现过的道具/地名 = 玩家看不懂。
 *     改稿时逐条 grep 主线确认，确认不了就删掉。
 *
 *  ② **选项文字必须是原文实际发生过的动作，不能是「聪明话」。**
 *     反例：正确选项写成角色「不可能预知」的信息 —— 那是编剧作弊，
 *     玩家选对了也不知道为什么对。正确选项要能被前文支撑。
 *
 *  ★ 会死的角色要**始终是同一个人**。分支设计上「谁都可能死」看着公平，
 *    实际会让每一条 END 都写不深 —— 死者的位置、关系、遗留问题全都要重写一遍。
 */

